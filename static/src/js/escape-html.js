// static/src/js/escape-html.js
//
// Экранирование пользовательских строк перед вставкой в innerHTML.
//
// Зачем: имена услуг, мастеров и клиентов подставлялись в шаблоны напрямую, а
// CSP у нас разрешает script-src 'unsafe-inline' — значит «PWN<img src=x
// onerror=…>» в названии услуги исполнялся у КАЖДОГО, кто открывал запись в
// этот салон. Владелец салона мог атаковать посетителей, а обычный клиент —
// владельца (его имя видно в панели «Обзор»).
//
// Где можно, лучше textContent; здесь же строки собираются шаблонами, поэтому
// каждое подставляемое значение прогоняем через esc().
export function esc(value) {
    if (value === null || value === undefined) return '';
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
