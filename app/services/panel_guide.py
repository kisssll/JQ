#: Что показать вместо описания, которого ещё нет.
MANUAL_PLACEHOLDER = "<p>Инструкция появится здесь.</p>"

#: Все ключи, по которым бывает реплика тура, — включая те, что не являются
#: разделами панели (второй шаг «Моей карточки мастера»). Нужен тестам на
#: длину реплики и на запрещённые обещания: по ALL_KEYS такой ключ не нашли бы.
TOUR_KEYS = frozenset(_TOUR) | frozenset(_TOUR_SOLO)


def tour_line(key: str, *, solo: bool = False) -> str:
    """Короткая реплика раздела для полосы тура."""
    if solo and key in _TOUR_SOLO:
        return _TOUR_SOLO[key]
    return _TOUR.get(key, "")


def manual_html(key: str, *, solo: bool = False) -> str:
    """Подробное описание раздела для вкладки «Инструкция»."""
    if solo and key in _MANUAL_SOLO:
        return _MANUAL_SOLO[key]
    return _MANUAL.get(key) or MANUAL_PLACEHOLDER


def has_manual(key: str, *, solo: bool = False) -> bool:
    if solo and key in _MANUAL_SOLO:
        return True
    return bool(_MANUAL.get(key))


def manual_sections(mode: Optional[SalonPanelMode] = None):
    """Разделы для справочника: (ключ, подпись, описание).

    Подпись берём из panel_sections, а не храним свою копию: иначе в соло
    справочник говорил бы «Сотрудники» про раздел, который в панели называется
    «Моя карточка мастера». Порядок — канонический: справочник читают как
    оглавление, а не как свою панель.

    Разделы, которых в режиме нет вовсе, в справочник не попадают: в соло
    «Редактировать салон» не существует, и описывать его человеку, у которого
    этого раздела нет, значит отправлять его искать несуществующую вкладку.
    """
    mode = mode or SalonPanelMode.TEAM
    solo = mode is SalonPanelMode.SOLO
    available = panel_sections.available_keys(mode)
    return [
        (key, panel_sections.label(key, mode), manual_html(key, solo=solo))
        for key in panel_sections.ALL_KEYS
        if key in available and has_manual(key, solo=solo)
    ]


