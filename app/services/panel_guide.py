def has_manual(key: str, *, solo: bool = False) -> bool:
    why, body = manual_text(key, solo=solo)
    return bool(why and body)


def _targets(key: str, mode: SalonPanelMode, solo: bool) -> Tuple[Target, ...]:
    if solo and key in _TARGETS_SOLO:
        return tuple(
            Target(tab=key, anchor=anchor, caption=word(word_key, solo=True))
            for anchor, word_key in _TARGETS_SOLO[key]
        )
    return (Target(tab=key, anchor=None, caption=panel_sections.label(key, mode)),)


def manual_sections(
    mode: Optional[SalonPanelMode] = None, visible_keys: Optional[Iterable[str]] = None,
) -> List[Section]:
    """Подразделы справочника плоским списком, в порядке чтения.

    Подпись берём из panel_sections, а не храним свою копию: иначе в соло
    справочник говорил бы «Сотрудники» про раздел, который в панели называется
    «Моя карточка мастера».

    visible_keys — итоговая видимость разделов из панели: раздел включён у
    салона И право на него есть. Передаётся готовым списком, тем же, по
    которому строятся меню и тур: справочник не имеет права вести в раздел,
    которого у человека нет, — такая ссылка молча вернула бы его в «Обзор».
    Без него берём всё, что бывает в режиме.
    """
    mode = mode or SalonPanelMode.TEAM
    solo = mode is SalonPanelMode.SOLO
    present = (
        frozenset(visible_keys) if visible_keys is not None
        else panel_sections.available_keys(mode)
    ) & panel_sections.available_keys(mode)
    out: List[Section] = []
    for _slug, _title, _lead, keys in _GROUPS:
        for key in keys:
            if key not in present or not has_manual(key, solo=solo):
                continue
            why, body = manual_text(key, solo=solo)
            out.append(Section(
                key=key, label=panel_sections.label(key, mode),
                why=why, body=body, targets=_targets(key, mode, solo),
            ))
    return out


def manual_groups(
    mode: Optional[SalonPanelMode] = None, visible_keys: Optional[Iterable[str]] = None,
) -> List[Group]:
    """То же, но группами — так справочник и читается (решение 0009, п. 7).

    Группа, у которой не осталось ни одной секции, не отдаётся вовсе: пустой
    заголовок «Пригодится позже» без содержимого — это обещание, которого на
    странице нет.
    """
    mode = mode or SalonPanelMode.TEAM
    by_key = {s.key: s for s in manual_sections(mode, visible_keys)}
    out: List[Group] = []
    for slug, title, lead, keys in _GROUPS:
        inside = tuple(by_key[k] for k in keys if k in by_key)
        if inside:
            out.append(Group(key=slug, title=title, lead=lead, sections=inside))
    return out


def start_steps(mode: Optional[SalonPanelMode] = None):
    """Шаги «с чего начать»: (заголовок, где искать, текст).

    «Где искать» — это НЕ строка с названием вкладки, а ключи разделов (или
    SAME_PLACE — «там же»): название приходит из panel_sections.label по
    режиму. Зашитое строкой название стало бы прямой ложью — отправило бы
    человека искать вкладку, которой у него нет.
    """
    if mode is SalonPanelMode.SOLO:
        return _START_STEPS_SOLO
    return _START_STEPS


