def word(key: str, *, solo: bool) -> str:
    """Подпись для этого места панели. Неизвестный ключ — пустая строка.

    Пустая строка возвращается и там, где у места есть вариант только для
    одного режима (например две группы раздела существуют лишь в соло):
    подставлять чужой вариант вместо отсутствующего нельзя, иначе подпись
    соврёт, а не промолчит.
    """
    pair = _WORDS.get(key)
    if pair is None:
        return ""
    return pair[0] if solo else pair[1]


def words_for(mode: SalonPanelMode):
    """Готовая функция одной подписи для режима: ``w = words_for(mode)``.

    Нужна разметке: в одном шаблоне подписей бывает десяток, и повторять
    ``solo=solo`` в каждой — шум, который легко перепутать местами.
    """
    solo = mode is SalonPanelMode.SOLO

    def _w(key: str) -> str:
        return word(key, solo=solo)

    return _w


