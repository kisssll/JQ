# app/services/bot_texts.py
"""Тексты и подписи кнопок, общие для всех трёх ботов.

Раньше одни и те же слова лежали в tg_bot.py, max_bot.py и vk_bot.py, и
правка требовала трёх одинаковых изменений в трёх файлах. Разъезжались они
именно так: MAX год умел только подтверждать номер, пока его не подтянули
к остальным отдельной работой.

Тексты держим короткими: человек открывает бота с задачей, а не читать.
"""
from __future__ import annotations

# ── подписи кнопок меню ─────────────────────────────────────────────────────
MENU_BOOKINGS = "📅 Мои записи"
MENU_PREFS = "⚙️ Мои уведомления"
#: «Написать нам» звучало как «отправьте нам письмо». Человек приходит сюда
#: с вопросом или проблемой — так кнопку и называем.
MENU_SUPPORT = "❓ Другой вопрос"
MENU_LINK = "🔗 Привязать аккаунт"
MENU_CONTEST = "🎃 Участвовать в конкурсе"

# ── первый контакт ──────────────────────────────────────────────────────────
#: Без «лучших мастеров»: превосходство в рекламе нужно доказывать
#: (п. 1 ч. 3 ст. 5 закона «О рекламе»), а проверить его мы не можем —
#: в каталоге все, кто подключился.
GREETING = (
    "Привет! Это Руми — сервис, где можно записаться к мастерам вашего города "
    "или вести свой бизнес."
)

#: Второе сообщение — только тем, у кого аккаунт не привязан.
LINK_OFFER = (
    "Привяжите аккаунт Руми — и уведомления о записях будут приходить сюда.\n\n"
    "Если вопрос о другом, нажмите «{support}»."
).format(support=MENU_SUPPORT)


def menu_hint(*, with_contest: bool = False) -> str:
    """Что умеет бот — для привязанного человека."""
    lines = [
        f"{MENU_BOOKINGS} — ближайшие записи, можно отменить",
        f"{MENU_PREFS} — какие уведомления присылать",
        f"{MENU_SUPPORT} — вопрос или проблема, ответим сюда же",
    ]
    if with_contest:
        lines.insert(0, f"{MENU_CONTEST} — конкурс мастеров")
    return "\n".join(lines)


def hello(user) -> str:
    """Приветствие привязанного: по имени, если оно известно."""
    name = (getattr(user, "full_name", "") or "").split()
    return f"Здравствуйте, {name[0]}!" if name else "Здравствуйте!"


# ── привязка ────────────────────────────────────────────────────────────────

def link_done(channel_label: str | None = None) -> str:
    """Подтверждение привязки. channel_label — канал, который остаётся
    основным, если он был; None — уведомления пойдут в этот мессенджер."""
    if channel_label:
        return ("Аккаунт Руми привязан ✅\n\n"
                f"Сейчас уведомления о записях приходят в {channel_label}. "
                "Присылать их сюда?")
    return "Аккаунт Руми привязан ✅\nУведомления о записях будут приходить сюда."


# ── ВКонтакте: два сообщества (решение 0013) ────────────────────────────────
# Клиентское и бизнесовое сообщества — разные боты с разными меню, а не одно
# меню на всех: клиенту незачем «тариф», мастеру — «вечерние окна».
# Telegram и MAX этих текстов не используют.

MENU_EVENING = "🌙 Вечерние окна"
MENU_PANEL = "📋 Заявки и записи"
MENU_TARIFF = "💳 Тариф и оплата"
MENU_SALON_SUPPORT = "❓ Поддержка для салонов"

#: Что приходит в каждое сообщество — повторяется в приглашении и в
#: подтверждении привязки, чтобы человек понимал, зачем ему второй диалог.
VK_CLIENT_GETS = "напоминания о записях, отмены и вопросы об отзыве"
VK_BUSINESS_GETS = "новые записи к вам, сообщения о тарифе и оплате, ответы поддержки"


def vk_menu_hint(audience: str, *, with_contest: bool = False) -> str:
    """Что умеет бот этого сообщества — для привязанного человека."""
    if audience == "client":
        return "\n".join([
            f"{MENU_BOOKINGS} — ближайшие записи, можно отменить",
            f"{MENU_PREFS} — напоминания, вопросы об отзыве, вечерние окна",
            f"{MENU_EVENING} — свободные вечерние окна со скидкой",
        ])
    lines = [
        f"{MENU_PANEL} — новые записи в панели салона",
        f"{MENU_TARIFF} — тариф и оплата",
        f"{MENU_SALON_SUPPORT} — вопрос или проблема, ответим сюда же",
    ]
    if with_contest:
        lines.insert(0, f"{MENU_CONTEST} — конкурс мастеров")
    return "\n".join(lines)


def vk_link_offer(audience: str) -> str:
    """Приглашение привязать аккаунт — тем, кого бот не узнал."""
    if audience == "client":
        return f"Привяжите аккаунт Руми — и сюда будут приходить {VK_CLIENT_GETS}."
    return (f"Привяжите аккаунт Руми — и сюда будут приходить {VK_BUSINESS_GETS}.\n\n"
            f"Если вопрос о другом, нажмите «{MENU_SALON_SUPPORT}».")


def vk_link_done(audience: str, channel_label: str | None = None, *,
                 recognized: bool = False) -> str:
    """Подтверждение привязки к сообществу.

    recognized — человек уже привязан к Руми через этот аккаунт ВК (входом
    через VK ID или другим сообществом), и код у него не спрашивали: говорим,
    что узнали, а не «привязан», иначе непонятно, что произошло.
    channel_label — канал, который остаётся основным, если он был.
    """
    gets = VK_CLIENT_GETS if audience == "client" else VK_BUSINESS_GETS
    head = ("Узнали вас: этот аккаунт ВКонтакте уже привязан к Руми ✅"
            if recognized else "Аккаунт Руми привязан ✅")
    if channel_label:
        return (f"{head}\n\nСейчас уведомления приходят в {channel_label}. "
                "Присылать их сюда?")
    return f"{head}\nСюда будут приходить {gets}."
