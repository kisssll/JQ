#: Имена с беглой гласной и прочие, где общее правило даёт неверный падеж.
#: Список короткий намеренно: сюда попадает только то, что действительно
#: встречается, иначе это превращается в словарь имён вместо правила.
_DATIVE_EXCEPTIONS = {
    "павел": "Павлу",
    "лев": "Льву",
    "пётр": "Петру",
    "петр": "Петру",
    # Женское на «‑ь» склоняется в «‑и», мужское — в «‑ю», и по виду слова их
    # не отличить («Любовь» против «Игорь»). Общее правило оставлено мужским.
    "любовь": "Любови",
}

_VOWELS_NO_CHANGE = "оеёиыуюэ"
_CYRILLIC = set("абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ-")


def first_name(full_name: str) -> str:
    """Первое слово имени. «Записаться к Анне Ивановне Смирновой» — это не
    обращение, а строка из паспорта; клиент говорит «к Анне»."""
    return (full_name or "").strip().split()[0] if (full_name or "").strip() else ""


def dative(name: str) -> str:
    """Имя в дательном падеже («Анна» → «Анне»), или пустая строка, если
    уверенности нет.

    Падеж нужен, потому что «Записаться к Анна» читается хуже, чем отсутствие
    имени вовсе. Поэтому правило одно, оно явное, и при любом сомнении —
    пустая строка: вызывающий тогда берёт подпись без имени.

    Правила (русские личные имена):
      * «‑ия» → «‑ии» (Мария → Марии), «‑я» → «‑е» (Настя → Насте);
      * «‑а» → «‑е» (Анна → Анне, Ольга → Ольге);
      * «‑ь», «‑й» → «‑ю» (Игорь → Игорю, Алексей → Алексею);
      * прочие согласные → «+у» (Иван → Ивану);
      * прочие гласные — несклоняемые имена (Нино, Отто), остаются как есть.
    Нерусское или непохожее на имя (цифры, латиница, название салона из двух
    слов) падежа не получает.
    """
    name = (name or "").strip()
    if not name or len(name) < 2:
        return ""
    # Только буквы кириллицы: «Hair Studio» и «ООО Ромашка» склонять нечего.
    if any(ch not in _CYRILLIC for ch in name):
        return ""

    # Строка капсом — это не имя, а вывеска («ООО», «SPA»): падежа не даём.
    if name.upper() == name and len(name) > 2:
        return ""

    low = name.lower()
    if low in _DATIVE_EXCEPTIONS:
        return _DATIVE_EXCEPTIONS[low]

    last = low[-1]
    if low.endswith("ия"):
        return name[:-1] + "и"
    if last == "я":
        return name[:-1] + "е"
    if last == "а":
        return name[:-1] + "е"
    if last in ("ь", "й"):
        return name[:-1] + "ю"
    if last in _VOWELS_NO_CHANGE:
        return name
    if last == "ъ":
        return ""
    return name + "у"


def solo_from_facts(panel_mode, master_count: int, master_is_creator: bool = False) -> bool:
    """Соло — когда за страницей стоит один человек, а не организация.

    Два признака, и оба нужны: мастер на салоне РОВНО ОДИН (иначе «Записаться
    к Анне» прячет Бориса) и владелец либо сам этот мастер, либо он объявил
    режим «работаю один» в панели. Объявленный режим учитывается потому, что
    он и есть ответ владельца на этот вопрос; структурная проверка — потому
    что режим по умолчанию SOLO у всех, включая того, кто панель не открывал.

    Отдельная функция на голых значениях, а не только на ORM-объектах: каталог
    собирает страницу одним SQL-запросом и объектов салона не держит вовсе.
    Режим приходит и перечислением, и его строковым именем (из SQL).
    """
    if master_count != 1:
        return False
    declared = panel_mode is SalonPanelMode.SOLO or str(
        getattr(panel_mode, "value", panel_mode) or ""
    ).lower() == "solo"
    return bool(declared or master_is_creator)


def is_solo(salon, masters) -> bool:
    """То же решение для страницы, у которой есть салон и список мастеров."""
    if len(masters) != 1:
        return False
    return solo_from_facts(
        getattr(salon, "panel_mode", None),
        1,
        masters[0].user_id == getattr(salon, "creator_id", None),
    )


def word(key: str, *, solo: bool, name: str = "") -> str:
    """Подпись для этого места витрины. Неизвестный ключ — пустая строка.

    Если в шаблоне есть ``{name}``, а имени не дали, возвращается вариант
    противоположного режима БЕЗ имени — но только когда он существует.
    Подставлять «Записаться к » с пустым хвостом нельзя: это не тихая
    деградация, а сломанная подпись.
    """
    pair = _WORDS.get(key)
    if pair is None:
        return ""
    template = pair[0] if solo else pair[1]
    if "{name}" not in template:
        return template
    if not name:
        fallback = pair[1] if solo else pair[0]
        return fallback if "{name}" not in fallback else ""
    return template.format(name=name)


def words_for(salon, masters, holder_name: str = ""):
    """``w, solo = words_for(salon, masters, "Анна Смирнова")`` — готовая
    функция одной подписи.

    Имя для ``{name}`` модуль ставит сам: в соло — имя мастера в дательном
    падеже, в команде — название салона. Иначе каждая страница решала бы это
    по-своему, и падеж разъехался бы с режимом. ``holder_name`` передаёт
    вызывающий: имя мастера лежит в ``User``, а грузить его отношением здесь
    значит сходить в базу из функции подписей.
    """
    solo = is_solo(salon, masters)
    name = dative(first_name(holder_name)) if solo else (getattr(salon, "name", "") or "")

    def _w(key: str) -> str:
        return word(key, solo=solo, name=name)

    return _w, solo


