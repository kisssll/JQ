# app/web/components/escaping.py
"""Экранирование пользовательского текста для серверных шаблонов.

Страницы собираются f-строками, а не шаблонизатором с автоэкранированием,
поэтому каждое подставляемое значение нужно пропускать через e() вручную.

Почему это критично: имя мастера, услуги или клиента задаёт пользователь, а
CSP у нас разрешает script-src 'unsafe-inline' — строка вида
«Имя<img src=x onerror=…>» исполнялась у КАЖДОГО, кто открывал страницу
салона (аноним, без единого действия). Клиент мог сменить своё ФИО и
атаковать владельца в панели записей.

e() безопасно принимает None и не-строки и всегда экранирует кавычки —
одинаково годится и для текста, и для значения атрибута.
"""
import html
import json as _json
from typing import Any


def e(value: Any) -> str:
    """Текст пользователя → безопасная вставка в HTML (в т.ч. в атрибут)."""
    if value is None:
        return ""
    return html.escape(str(value), quote=True)


def ejson(value: Any) -> str:
    """JSON для data-атрибута: сериализуем и экранируем кавычки.

    Без экранирования апостроф в имени («O'Brien» или подобранный пейлоад)
    закрывал атрибут data-...='...' и позволял вписать свой HTML.
    """
    return html.escape(_json.dumps(value, ensure_ascii=False), quote=True)


def ejs(value: Any) -> str:
    """Строка пользователя внутри JS-вызова в HTML-атрибуте (onclick и т.п.).

    Одного экранирования мало: json.dumps даёт корректный JS-литерал (кавычки
    и спецсимволы внутри уже escaped), а html.escape поверх не даёт кавычкам
    закрыть сам атрибут. Прежний вариант (ручная замена только апострофа)
    ломался на двойной кавычке в названии услуги.
    """
    return e(_json.dumps("" if value is None else str(value), ensure_ascii=False))
